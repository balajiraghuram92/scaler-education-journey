from datetime import datetime
from decimal import ROUND_HALF_UP, Decimal
from typing import Literal, Self
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator, model_validator
from pydantic.alias_generators import to_camel

Currency = Literal["USD", "EUR", "INR", "JPY"]


class _Base(BaseModel):
    """Shared model config, declared once.

    Configure: alias_generator=to_camel, populate_by_name=True, extra="forbid", frozen=True.
    """


class InvoiceLine(_Base):
    """One invoice line (extends _Base). Fields:

    - sku: str matching ^[A-Z]{3}-\\d{4}$
    - qty: int > 0 in strict mode (the string "2" must be rejected)
    - unit_price: Decimal >= 0, at most 12 digits and 2 decimal places
    """


class Invoice(_Base):
    """An invoice (extends _Base). Fields:

    - id: UUID, generated by default
    - currency: Currency
    - lines: list[InvoiceLine] with at least one line
    - discount_pct: Decimal between 0 and 100, default Decimal("0")
    - issued_at: datetime, must be timezone-aware (message must contain "timezone-aware")

    Also required:
    - a model validator (mode="after") rejecting JPY invoices whose unit prices have a fractional part
    - computed fields (output only, never accepted as input):
        subtotal = sum(qty * unit_price)
        total    = subtotal * (100 - discount_pct) / 100, quantized to 0.01 with ROUND_HALF_UP
    """
